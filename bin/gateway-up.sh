#!/usr/bin/env bash
# Start the fleet's LiteLLM model gateway.
#
#   bin/gateway-up.sh                          # every class must be credentialled
#   bin/gateway-up.sh --allow-missing local    # run without the local class, on purpose
#   bin/gateway-up.sh --dry-run                # compose and validate, start nothing
#
# The gateway serves API-key traffic only: the Anthropic API, hosted cheap
# models, and local open-weight models. Claude Code sessions authenticate
# against a subscription and cannot be routed through here at all — see
# docs/agent-gateway.md, and bin/claude-accounts.sh for managing those.
#
# A missing credential is a hard stop, not a downgrade. The alternative — drop
# the class and let the router find something else — turns "the Anthropic key
# expired" into "reviews got quietly worse", which is the failure this script
# exists to make impossible.
set -euo pipefail

HERE="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
# shellcheck source=gateway-common.sh
. "$HERE/gateway-common.sh"

ALLOW_MISSING=""
DRY_RUN=0
while [ $# -gt 0 ]; do
  case "$1" in
    --allow-missing) ALLOW_MISSING="$ALLOW_MISSING,${2:-}"; shift 2 ;;
    --allow-missing=*) ALLOW_MISSING="$ALLOW_MISSING,${1#*=}"; shift ;;
    --dry-run) DRY_RUN=1; shift ;;
    --port) GATEWAY_PORT="${2:-}"; shift 2 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "gateway-up: unknown argument: $1" >&2; exit 2 ;;
  esac
done

allowed_missing() {
  case ",$ALLOW_MISSING," in *",$1,"*) return 0 ;; esac
  return 1
}

command -v litellm >/dev/null 2>&1 || {
  cat >&2 <<'MSG'
gateway-up: `litellm` is not on PATH.

Install it as a user-level tool (there is no Docker daemon on this box):

    uv tool install 'litellm[proxy]'

MSG
  exit 1
}

[ -r "$GATEWAY_MANIFEST" ] || { echo "gateway-up: no class manifest at $GATEWAY_MANIFEST" >&2; exit 1; }

mkdir -p "$CLAUDE_GATEWAY_HOME"
chmod 700 "$CLAUDE_GATEWAY_HOME"

if gateway_is_up; then
  echo "gateway-up: already running (pid $(gateway_pid)) on $(gateway_url)."
  echo "            Stop it with bin/gateway-down.sh before starting another."
  exit 0
fi
# A stale PID file from a killed process must not block a restart, but a port
# already taken by something else must — two proxies on one port is a bug that
# presents as intermittent 404s for half the classes.
rm -f "$GATEWAY_PID_FILE"
if curl -fsS -m 2 -o /dev/null "$(gateway_url)/health/readiness" 2>/dev/null; then
  echo "gateway-up: something is already serving $(gateway_url) and it is not ours." >&2
  echo "            Pick another port with --port, or find the owner." >&2
  exit 1
fi

gateway_load_secrets

# --- Preflight -------------------------------------------------------------
LIVE=""
SKIPPED=""
BLOCKED=""
while IFS='|' read -r name keys fallbacks probe; do
  [ -n "$name" ] || continue
  blocker="$(gateway_class_blocker "$keys" "$probe")"
  if [ -z "$blocker" ]; then
    LIVE="$LIVE $name"
  elif allowed_missing "$name"; then
    SKIPPED="$SKIPPED|$name: $blocker"
  else
    BLOCKED="$BLOCKED|$name: $blocker"
  fi
done < <(gateway_classes)

if [ -n "$BLOCKED" ]; then
  echo "gateway-up: refusing to start — these classes have no working credential:" >&2
  echo "$BLOCKED" | tr '|' '\n' | sed '/^$/d;s/^/  ✗ /' >&2
  cat >&2 <<'MSG'

Fix the credential, or run the class out on purpose:

    bin/gateway-up.sh --allow-missing <class>

Starting without it silently would route that class's work somewhere cheaper
and never say so. See docs/agent-gateway.md → Failure modes.
MSG
  exit 1
fi

LIVE="${LIVE# }"
[ -n "$LIVE" ] || { echo "gateway-up: every class was skipped — nothing to serve." >&2; exit 1; }

# --- Compose the runtime config -------------------------------------------
is_live() {
  case " $LIVE " in *" $1 "*) return 0 ;; esac
  return 1
}

tmp_config="$(mktemp "$CLAUDE_GATEWAY_HOME/.runtime-config.XXXXXX")"
{
  echo "# GENERATED by bin/gateway-up.sh from gateway/config.yaml + gateway/classes/."
  echo "# Edit those, not this. Regenerated on every start; safe to delete."
  echo "# Composed $(date -u +%Y-%m-%dT%H:%M:%SZ) with classes: $LIVE"
  echo
  cat "$GATEWAY_CONFIG_DIR/config.yaml"
  echo
  echo "model_list:"
  for c in $LIVE; do
    cat "$GATEWAY_CONFIG_DIR/classes/$c.yaml"
  done
  echo
  echo "router_settings:"
  echo "  routing_strategy: simple-shuffle"
  echo "  num_retries: 2"
  echo "  allowed_fails: 3"
  echo "  cooldown_time: 60"
  echo "  fallbacks:"
  fb_count=0
  while IFS='|' read -r name _keys fallbacks _probe; do
    [ -n "$name" ] || continue
    is_live "$name" || continue
    targets=""
    IFS=',' read -r -a want <<< "$fallbacks"
    for t in "${want[@]}"; do
      [ -n "$t" ] || continue
      # A fallback naming a class that is not running is worse than no
      # fallback: it turns a clean upstream error into a routing error.
      is_live "$t" || continue
      targets="$targets, \"$t\""
    done
    [ -n "$targets" ] || continue
    echo "    - {\"$name\": [${targets#, }]}"
    fb_count=$((fb_count + 1))
  done < <(gateway_classes)
  [ "$fb_count" -gt 0 ] || echo "    []"
} > "$tmp_config"

python3 - "$tmp_config" <<'PY' || { echo "gateway-up: composed config is not valid YAML (see above)" >&2; exit 1; }
import sys
try:
    import yaml
except ImportError:
    sys.exit(0)  # no parser here; litellm will do its own validation at start
with open(sys.argv[1]) as fh:
    doc = yaml.safe_load(fh)
names = [m["model_name"] for m in doc.get("model_list", [])]
assert names, "composed config has no model_list"
live = set(names)
for entry in doc.get("router_settings", {}).get("fallbacks") or []:
    for src, dests in entry.items():
        assert src in live, f"fallback source {src} is not a live class"
        for d in dests:
            assert d in live, f"{src} falls back to {d}, which is not running"
PY

mv "$tmp_config" "$GATEWAY_RUNTIME_CONFIG"

# --- Master key ------------------------------------------------------------
if [ ! -s "$GATEWAY_MASTER_KEY_FILE" ]; then
  umask 077
  printf 'sk-%s\n' "$(head -c 24 /dev/urandom | od -An -tx1 | tr -d ' \n')" > "$GATEWAY_MASTER_KEY_FILE"
fi
chmod 600 "$GATEWAY_MASTER_KEY_FILE"
LITELLM_MASTER_KEY="$(cat "$GATEWAY_MASTER_KEY_FILE")"
export LITELLM_MASTER_KEY

# Single-quoted, because a blocker string contains the literal `$NAME` of the
# variable that was missing. Double-quoted, sourcing this file would try to
# EXPAND that name, and under `set -u` the status command dies on the very
# variable whose absence it is reporting.
sq() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }
{
  echo "GATEWAY_PORT=$GATEWAY_PORT"
  echo "GATEWAY_HOST=$GATEWAY_HOST"
  echo "GATEWAY_LIVE_CLASSES=$(sq "$LIVE")"
  echo "GATEWAY_SKIPPED=$(sq "${SKIPPED#|}")"
  echo "GATEWAY_STARTED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)"
} > "$GATEWAY_STATE_FILE"

if [ "$DRY_RUN" = 1 ]; then
  echo "gateway-up: dry run. Composed $GATEWAY_RUNTIME_CONFIG"
  echo "            classes: $LIVE"
  [ -n "$SKIPPED" ] && echo "$SKIPPED" | tr '|' '\n' | sed '/^$/d;s/^/            skipped: /'
  exit 0
fi

# --- Start -----------------------------------------------------------------
{
  echo
  echo "=== gateway-up $(date -u +%Y-%m-%dT%H:%M:%SZ) classes: $LIVE ==="
} >> "$GATEWAY_LOG_FILE"

nohup litellm --config "$GATEWAY_RUNTIME_CONFIG" \
  --host "$GATEWAY_HOST" --port "$GATEWAY_PORT" \
  >> "$GATEWAY_LOG_FILE" 2>&1 &
pid=$!
echo "$pid" > "$GATEWAY_PID_FILE"

for _ in $(seq 1 60); do
  if gateway_ready; then
    echo "gateway-up: listening on $(gateway_url) (pid $pid)"
    echo "            classes: $LIVE"
    [ -n "$SKIPPED" ] && echo "$SKIPPED" | tr '|' '\n' | sed '/^$/d;s/^/            skipped on purpose: /'
    echo "            log:     $GATEWAY_LOG_FILE"
    echo "            key:     $GATEWAY_MASTER_KEY_FILE"
    exit 0
  fi
  kill -0 "$pid" 2>/dev/null || break
  sleep 1
done

echo "gateway-up: proxy did not become ready. Last log lines:" >&2
tail -n 30 "$GATEWAY_LOG_FILE" >&2
kill "$pid" 2>/dev/null || true
rm -f "$GATEWAY_PID_FILE"
exit 1
